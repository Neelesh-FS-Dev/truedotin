// Builds web media from the original files in the project root. Originals are never modified.
// Photos (macOS sips): AVIF + JPEG at 640 and 1280 px (longest side).
// Videos (ffmpeg): 15 s, audio removed, H.264 720x1280 (never upscaled), poster frame at 1 s.
// Requires: macOS sips, and ffmpeg/ffprobe on PATH (brew install ffmpeg).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public/media');
const PREVIEW_SECONDS = 15;
// Not exported: a073 and a074 duplicate a072; a080 has no clear campaign context and rights pending;
// a101 and a109 are motion blur with no subject.
const EXCLUDED = new Set(['a073', 'a074', 'a080', 'a101', 'a109']);

const sources = readdirSync(ROOT).filter((f) => /^truedotin_.*\.(jpg|mp4)$/.test(f)).sort();
rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'photos'), { recursive: true });
mkdirSync(join(OUT, 'video'), { recursive: true });

const sipsSize = (file, key) => Number(execFileSync('sips', ['-g', key, file]).toString().match(new RegExp(`${key}: (\\d+)`))[1]);
const probe = (file) => {
  const [w, h] = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0:s=x', file]).toString().trim().split('x').map(Number);
  if (!w || !h) throw new Error(`no video stream in ${file}`);
  return { w, h };
};

const manifest = [];
for (const [index, file] of sources.entries()) {
  const id = `a${String(index + 1).padStart(3, '0')}`;
  if (EXCLUDED.has(id)) continue;
  const src = join(ROOT, file);
  if (file.endsWith('.jpg')) {
    for (const size of [640, 1280]) {
      execFileSync('sips', ['-Z', String(size), '-s', 'format', 'avif', '-s', 'formatOptions', '60', src, '--out', join(OUT, 'photos', `${id}-${size}.avif`)], { stdio: 'ignore' });
      execFileSync('sips', ['-Z', String(size), '-s', 'format', 'jpeg', '-s', 'formatOptions', '80', src, '--out', join(OUT, 'photos', `${id}-${size}.jpg`)], { stdio: 'ignore' });
    }
    manifest.push({ id, kind: 'photo', w: sipsSize(src, 'pixelWidth'), h: sipsSize(src, 'pixelHeight') });
  } else {
    const mp4 = join(OUT, 'video', `${id}.mp4`);
    const poster = join(OUT, 'video', `${id}-poster.jpg`);
    execFileSync('ffmpeg', [
      '-v', 'error', '-y', '-i', src, '-t', String(PREVIEW_SECONDS), '-an',
      '-vf', 'scale=720:1280:force_original_aspect_ratio=decrease,pad=ceil(iw/2)*2:ceil(ih/2)*2',
      '-c:v', 'libx264', '-preset', 'slow', '-crf', '27', '-profile:v', 'high', '-pix_fmt', 'yuv420p',
      '-movflags', '+faststart', mp4,
    ], { stdio: 'inherit' });
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-ss', '1', '-i', mp4, '-frames:v', '1', '-q:v', '3', poster], { stdio: 'ignore' });
    const { w, h } = probe(mp4);
    manifest.push({ id, kind: 'video', w, h, dur: PREVIEW_SECONDS });
  }
  console.log('exported', id);
}

const body = manifest.map((m) => `  ${m.id}: ${JSON.stringify(m)},`).join('\n');
writeFileSync(join(ROOT, 'src/content/media.generated.ts'),
`// Generated by scripts/build-media.mjs. Do not edit by hand.
export type MediaItem = { id: string; kind: 'photo' | 'video'; w: number; h: number; dur?: number };

export const MEDIA = {
${body}
} as const satisfies Record<string, MediaItem>;

export type MediaId = keyof typeof MEDIA;
`);
console.log(`wrote ${manifest.length} media items`);
